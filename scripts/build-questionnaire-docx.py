# -*- coding: utf-8 -*-
"""Опросный лист для Заказчика — данные, необходимые для оформления договора.

Запуск: python scripts/build-questionnaire-docx.py
"""
from docx.enum.text import WD_ALIGN_PARAGRAPH as AL

from docxkit import bullet, h, new_doc, para, save, table, title

LINE = "_" * 60


def field(d, label, hint=None):
    p = d.add_paragraph()
    p.paragraph_format.space_after = 2
    r = p.add_run(label + ": ")
    r.bold = True
    p.add_run(LINE)
    if hint:
        para(d, hint, indent=0.6, italic=True, size=9)


def build():
    d = new_doc()
    title(d, "ОПРОСНЫЙ ЛИСТ ЗАКАЗЧИКА",
          "Сведения, необходимые для оформления договора на разработку "
          "интернет-магазина «ТрудКрутШоп»")
    para(d, "Заполните, пожалуйста, поля ниже и верните файл. На основании этих сведений "
            "будет подготовлен договор с приложениями к подписанию. "
            "Поля, отмеченные знаком «*», обязательны.", italic=True)

    h(d, "1. Сведения об организации")
    for label, hint in [
        ("Полное наименование организации *", "как в ЕГРЮЛ, включая организационно-правовую форму"),
        ("Сокращённое наименование", None),
        ("ИНН *", None),
        ("КПП", "для ООО; ИП не заполняет"),
        ("ОГРН / ОГРНИП *", None),
        ("Юридический адрес *", "с почтовым индексом"),
        ("Почтовый (фактический) адрес *", None),
        ("Система налогообложения *", "ОСНО, УСН «доходы», УСН «доходы минус расходы», иное"),
        ("Является ли плательщиком НДС *", "да / нет; если да — применяемые ставки"),
    ]:
        field(d, label, hint)

    h(d, "2. Банковские реквизиты")
    for label, hint in [
        ("Расчётный счёт *", None),
        ("Наименование банка *", None),
        ("БИК *", None),
        ("Корреспондентский счёт *", None),
    ]:
        field(d, label, hint)

    h(d, "3. Подписант договора")
    for label, hint in [
        ("Фамилия, имя, отчество полностью *", None),
        ("Должность *", None),
        ("Действует на основании *", "устава / доверенности № ___ от ___ / свидетельства о регистрации ИП"),
        ("Телефон *", None),
        ("Адрес электронной почты *", "будет указан в договоре как юридически значимый"),
    ]:
        field(d, label, hint)

    h(d, "4. Уполномоченный представитель по проекту")
    para(d, "Сотрудник, который согласовывает промежуточные результаты, передаёт материалы "
            "и отвечает на вопросы в рабочем порядке.", italic=True, size=10)
    for label, hint in [
        ("Фамилия, имя, отчество *", None),
        ("Должность", None),
        ("Телефон *", None),
        ("Адрес электронной почты *", None),
        ("Предпочтительный канал оперативной связи", "Telegram, электронная почта, телефон"),
    ]:
        field(d, label, hint)

    d.add_page_break()

    h(d, "5. Согласованные коммерческие условия")
    para(d, "Условия ниже уже определены и включены в проект договора. "
            "Подтвердите их или предложите изменения.", italic=True, size=10)
    table(d, ["Условие", "Значение в проекте договора", "Отметка Заказчика"],
          [["Общая стоимость работ", "100 000 руб., НДС не облагается (самозанятый)",
            "согласовано / изменить"],
           ["Аванс", "50 % — 50 000 руб., в течение 3 рабочих дней с подписания",
            "согласовано / изменить"],
           ["Оплата остальной части", "по этапам, в течение 5 рабочих дней после акта",
            "согласовано / изменить"],
           ["Срок выполнения работ", "14 календарных дней от даты начала",
            "согласовано / изменить"],
           ["Дата начала работ", "________________ (заполняется Сторонами)",
            "«___» _______ 20___ г."],
           ["Срок рассмотрения акта Заказчиком", "1 рабочий день",
            "согласовано / изменить"],
           ["Автоматическая приёмка при отсутствии ответа", "предусмотрена",
            "согласовано / изменить"],
           ["Гарантийный срок", "3 месяца", "согласовано / изменить"],
           ["Реагирование на критичный дефект", "4 рабочих часа",
            "согласовано / изменить"],
           ["Реагирование на прочие дефекты", "3 рабочих дня", "согласовано / изменить"],
           ["Ставка на работы вне гарантии и допработы", "1 000 руб./час",
            "согласовано / изменить"],
           ["Конфиденциальность после окончания договора", "3 года",
            "согласовано / изменить"],
           ["Разрешение споров", "Новгородский районный суд Новгородской области",
            "согласовано / изменить"],
           ["Право Исполнителя показывать проект в портфолио", "предусмотрено",
            "согласовано / изменить"]],
          widths=[6.0, 6.4, 4.6], font=9)

    h(d, "6. Сведения для работы Сайта")
    for label, hint in [
        ("Формат выгрузки данных заказа для 1С и Контур.Диадок *",
         "какие поля нужны бухгалтерии для выпуска счёта и УПД"),
        ("Ставки НДС по категориям товаров *",
         "футболки, худи, значки, аксессуары, подарочные сертификаты"),
        ("Размер скидки для юридических лиц *", "процент и порог суммы заказа, если есть"),
        ("Домен Сайта *", "и у какого регистратора зарегистрирован"),
        ("Адрес действующего сайта *", None),
        ("Платёжный сервис", "подтверждено: Робокасса — укажите идентификатор магазина"),
        ("Облачная касса", "подтверждено: Бифит Касса — укажите, кто настраивает ставки НДС"),
        ("Служба доставки", "заключён ли договор, с какой службой"),
        ("Подключать ли сервис определения реквизитов по ИНН",
         "да / нет; при «нет» покупатель вводит реквизиты вручную"),
        ("Учётная система", "подтверждено: 1С; укажите конфигурацию и версию"),
        ("Кассовое оборудование офлайн-магазина", "производитель, модель, оператор фискальных данных"),
        ("Адрес склада отправления *", None),
    ]:
        field(d, label, hint)

    h(d, "7. Документы, которые нужно приложить")
    for t in [
        "Карточка организации с реквизитами.",
        "Свидетельство о постановке на учёт в налоговом органе или лист записи ЕГРЮЛ (ЕГРИП).",
        "Документ, подтверждающий полномочия подписанта: приказ о назначении или доверенность.",
        "Графические файлы подписи и печати для проекта счёта.",
        "Образец счёта, применяемого в организации.",
        "Логотип в векторном формате и брендбук.",
    ]:
        bullet(d, t)

    d.add_paragraph()
    para(d, "Заполненный опросный лист и приложенные документы направьте по адресу: "
            "________________________________.", italic=True)
    para(d, "Дата заполнения: «___» __________ 20___ г.        "
            "Заполнил: ______________ / ______________ /", align=AL.LEFT)

    return save(d, "10 Опросный лист Заказчика.docx")


if __name__ == "__main__":
    build()
